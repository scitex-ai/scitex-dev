"""§6 parity ratchet — a committed per-package baseline of missing MCP tools.

A package whose Python API is far larger than its MCP surface fails the
missing-tool half of §6 (more than half of its operations lack a tool)
long before the gap can be closed. Exempting it would also hide every
NEW function added without a tool. The ratchet records today's gap once
and then holds it: the baseline may only shrink.

File (in the audited repo, committed)::

    .scitex/dev/mcp-parity-baseline.yaml
    version: 1
    missing_mcp_tools:
      - annotate
      - apa_render

Semantics, applied by :func:`ratchet_violations` when the file exists:

- a Python API with no MCP tool that is NOT recorded → §6 error (new gap);
- a recorded API that now HAS a tool, or no longer exists → §6 error until
  the entry is deleted, so a closed gap cannot silently reopen later;
- recorded APIs that are still missing are the backlog: reported as a
  visible count, never as a violation.

The more-than-half threshold does not apply while a baseline exists: the
ratchet is exact. The orphan-tool half of §6 is unchanged.

Record (or re-record) with
``scitex-dev ecosystem audit-mcp-tools <pkg> --write-parity-baseline``;
growing the file is then a reviewable diff, never a side effect of an
audit run.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import yaml

from ._audit import Violation

__all__ = [
    "MCP_PARITY_BASELINE_RELPATH",
    "MalformedParityBaseline",
    "ParityBaseline",
    "format_backlog_notice",
    "load_parity_baseline",
    "ratchet_violations",
    "write_parity_baseline",
]

MCP_PARITY_BASELINE_RELPATH = Path(".scitex") / "dev" / "mcp-parity-baseline.yaml"

_VERSION = 1
_KEY = "missing_mcp_tools"


class MalformedParityBaseline(ValueError):
    """The baseline file exists but is not a valid ratchet file."""


@dataclass(frozen=True)
class ParityBaseline:
    """The recorded §6 backlog: Python APIs allowed to lack an MCP tool."""

    path: Path
    missing: frozenset[str]


def load_parity_baseline(root: Path | None) -> ParityBaseline | None:
    """Read ``<root>/.scitex/dev/mcp-parity-baseline.yaml``.

    Returns None when there is no audited tree or no file (the ratchet is
    opt-in by the file's existence). A file that exists but is malformed
    raises :class:`MalformedParityBaseline` — a corrupt ratchet silently
    suppressing nothing or everything would be undebuggable.
    """
    if root is None:
        return None
    path = Path(root) / MCP_PARITY_BASELINE_RELPATH
    if not path.is_file():
        return None
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise MalformedParityBaseline(f"{path}: not valid YAML ({exc})") from exc
    entries = data.get(_KEY) if isinstance(data, dict) else None
    if (
        not isinstance(data, dict)
        or data.get("version") != _VERSION
        or not isinstance(entries, list)
        or not all(isinstance(e, str) and e for e in entries)
    ):
        raise MalformedParityBaseline(
            f"{path}: expected `version: {_VERSION}` and a `{_KEY}:` list of "
            "Python API names — re-record with "
            "`scitex-dev ecosystem audit-mcp-tools <pkg> --write-parity-baseline`"
        )
    if len(set(entries)) != len(entries):
        raise MalformedParityBaseline(f"{path}: duplicate entries in `{_KEY}`")
    return ParityBaseline(path=path, missing=frozenset(entries))


def write_parity_baseline(root: Path, missing: set[str]) -> Path:
    """Record `missing` as the package's §6 backlog; returns the file path."""
    path = Path(root) / MCP_PARITY_BASELINE_RELPATH
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# §6 MCP-parity baseline — ratchet file (generated by\n"
        "# `scitex-dev ecosystem audit-mcp-tools <pkg> --write-parity-baseline`).\n"
        "# Python APIs listed here may lack an MCP tool for now. The list may\n"
        "# only SHRINK: a new API without a tool fails §6, and an entry whose\n"
        "# API gained a tool (or was removed) fails §6 until it is deleted.\n"
    )
    body = yaml.safe_dump({"version": _VERSION, _KEY: sorted(missing)}, sort_keys=False)
    path.write_text(header + body, encoding="utf-8")
    return path


def ratchet_violations(
    package: str, missing: set[str], baseline: ParityBaseline
) -> list[Violation]:
    """§6 missing-tool half under a baseline: new gaps and stale entries."""
    out: list[Violation] = []
    rel = MCP_PARITY_BASELINE_RELPATH
    new = set(missing) - baseline.missing
    if new:
        out.append(
            Violation(
                package,
                "§6",
                f"{len(new)} Python API(s) have no matching MCP tool and are "
                f"not in the parity baseline {rel}: {sorted(new)} — add an MCP "
                "tool for each (the baseline is a ratchet: it only shrinks)",
            )
        )
    stale = baseline.missing - set(missing)
    if stale:
        out.append(
            Violation(
                package,
                "§6",
                f"{len(stale)} parity-baseline entr{'y' if len(stale) == 1 else 'ies'}"
                f" in {rel} now have an MCP tool or no longer exist: "
                f"{sorted(stale)} — delete them from the baseline so the "
                "closed gap cannot silently reopen",
            )
        )
    return out


def format_backlog_notice(
    package: str, missing: set[str], baseline: ParityBaseline, n_apis: int
) -> str:
    """One visible line stating the remaining (recorded) §6 backlog."""
    backlog = len(set(missing) & baseline.missing)
    return (
        f"  [ratchet] {package}: §6 parity backlog {backlog}/{n_apis} Python "
        f"APIs without an MCP tool, recorded in {MCP_PARITY_BASELINE_RELPATH} "
        "(may only shrink)"
    )
