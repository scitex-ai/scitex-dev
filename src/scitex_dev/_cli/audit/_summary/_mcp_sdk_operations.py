"""§2 for SDK-derived MCP tools: judged by their operation, not by position.

A tool generated by scitex-sdk from an ``ApiOperation`` is named
``<package>_<resource>_<verb>`` (API contract v1, rule API-T001; operator
decision 1, 2026-11-28). The positional §2 reading (``<pkg>_<verb>_<noun>``)
would take the RESOURCE for the verb, so for these tools the verb is read from
the operation metadata itself and checked against the same synonym catalogue.

The SDK is optional for Dev: without it no tool is SDK-derived and §2 applies
unchanged. Discovery reads installed ``scitex.apis`` entry points of the
audited distribution only.
"""

from __future__ import annotations

import re


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name or "").lower()


def derived_tool_verbs_of(plugin) -> dict[str, str]:
    """``{mcp tool name: operation verb}`` of one SDK ``ApiPlugin``.

    Empty without scitex-sdk (optional for Dev): nothing is then derived.
    """
    try:
        from scitex_sdk.app.api_ops import operations
    except ImportError:
        return {}
    return {op.mcp_name: op.verb for op in operations(plugin)}


def derived_tool_verbs(package: str) -> dict[str, str]:
    """Every SDK-derived tool of ``package`` (distribution name), with its verb.

    Empty when scitex-sdk is not installed or the package declares no
    ``scitex.apis`` plugin. A plugin that cannot be loaded is not guessed at:
    its tools then fall back to the positional §2 check.
    """
    try:
        from scitex_sdk.app.api_plugin import discover_api_plugins
    except ImportError:
        return {}
    from importlib import import_module

    out: dict[str, str] = {}
    for ref in discover_api_plugins():
        if _normalize(ref.distribution) != _normalize(package):
            continue
        module, _, attr = ref.target.partition(":")
        try:
            plugin = getattr(import_module(module), attr)
            out.update(derived_tool_verbs_of(plugin))
        except Exception:  # noqa: BLE001 - an unloadable plugin is not derived
            continue
    return out
